export function nextPassageIndex(length, current, random = Math.random()) {
  if (
    !Number.isInteger(length) ||
    length < 2 ||
    !Number.isInteger(current) ||
    current < 0 ||
    current >= length ||
    random < 0 ||
    random >= 1 ||
    !Number.isFinite(random)
  )
    throw new RangeError('Invalid passage selection');
  return (current + 1 + Math.floor(random * (length - 1))) % length;
}

export function stats(
  target,
  typed,
  elapsed,
  attempts = typed.length,
  errors = 0,
) {
  let correct = 0;
  for (let i = 0; i < typed.length; i++) if (typed[i] === target[i]) correct++;
  return {
    correct,
    wpm: elapsed > 0 ? Math.round(correct / 5 / (elapsed / 60)) : 0,
    cpm: elapsed > 0 ? Math.round(correct / (elapsed / 60)) : 0,
    accuracy: attempts
      ? Math.round(((attempts - errors) / attempts) * 100)
      : 100,
    progress: target.length
      ? Math.round((typed.length / target.length) * 100)
      : 0,
  };
}
